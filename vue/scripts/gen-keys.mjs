// Pin the delivery signing keys into the bundle (HLD Target web §5.4): run at build time,
// never at run time. `node scripts/gen-keys.mjs [http://localhost:8100/api/client/signing-keys]`
import { writeFileSync } from 'node:fs'

const url = process.argv[2] ?? 'http://localhost:8100/api/client/signing-keys'
const res = await fetch(url)
if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
const { keys } = await res.json()
const pinned = keys.filter((k) => k.status !== 'REVOKED').map((k) => ({ keyId: k.keyId, publicKey: k.publicKey }))
const out = `// generated by scripts/gen-keys.mjs from ${url} — Ed25519 raw public keys (base64)
export const SDUI_KEYS: ReadonlyArray<{ keyId: string; publicKey: string }> = ${JSON.stringify(pinned, null, 2)}
`
writeFileSync(new URL('../src/sdui/keys.generated.ts', import.meta.url), out)
console.log(`pinned ${pinned.length} key(s): ${pinned.map((k) => k.keyId).join(', ')}`)
